  inspection_id: string;
  sequenceNumber: number; // 1 to 60
  timestamp: string;
  batch_id: string;
  line_id: string;
  station: string;
  component: string;
  image: string;
  result: 'GOOD' | 'DEFECT' | 'CRACK';
